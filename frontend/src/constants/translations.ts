export type TranslationKey = keyof typeof translations;

// Helper function to get bilingual text
export const getBilingualText = (key: TranslationKey): string => {
  const t = translations[key];
  return `${t.en} / ${t.kin}`;
};

// Helper function to get text in specific language
export const getText = (key: TranslationKey, lang: 'en' | 'kin' = 'en'): string => {
  return translations[key][lang];
};
